def load(path, delimiter=","):
    with open(path, newline="") as f:
        return list(csv.DictReader(f, delimiter=delimiter))


def num(s):
    s = (s or "").strip()
    return float(s) if s not in ("", "None", "n.a.") else None


def esc(s):
    return (s.replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")
             .replace("#", "\\#").replace("$", "\\$").replace("{", "\\{").replace("}", "\\}"))


def natural(name):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", name)]


def intval(v):
    return "" if v is None else str(int(round(v)))


def dec(v, places=4):
    """Rounded to `places` decimals, trailing zeros dropped (for S columns)."""
    if v is None:
        return ""
    s = f"{v:.{places}f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def longtable(spec, caption, label, head, rows, foot_note=None, size="\\footnotesize", colsep="4pt"):
    """A booktabs longtable inside a group with the given size."""
    ncol = len(head)
    h = " & ".join(head) + r" \\"
    out = [HEADER, "{" + size + SI + f"\\setlength{{\\tabcolsep}}{{{colsep}}}\\setlength{{\\LTcapwidth}}{{\\linewidth}}",
           f"\\begin{{longtable}}{{{spec}}}",
           f"\\caption{{{caption}}}\\label{{{label}}}\\\\",
           r"\toprule", h, r"\midrule", r"\endfirsthead",
           f"\\multicolumn{{{ncol}}}{{l}}{{\\emph{{(continued)}}}}\\\\", r"\toprule", h, r"\midrule", r"\endhead",
           r"\midrule", f"\\multicolumn{{{ncol}}}{{r}}{{\\emph{{continued on the next page}}}}\\\\", r"\endfoot",
           r"\bottomrule"]
    if foot_note:
        out.append(f"\\multicolumn{{{ncol}}}{{@{{}}p{{\\linewidth}}@{{}}}}{{{foot_note}}}\\\\")
    out.append(r"\endlastfoot")
    for r in rows:
        out.append(r if r.startswith("\\") else r + r" \\")
    out += [r"\end{longtable}", "}"]
    return "\n".join(out) + "\n"


def brace(s):
    return "{" + s + "}"


def name_list(names, mark=None, max_cols=5):
    """Names in a multicol list; the column count follows the longest name."""
    longest = max(len(n) for n in names)
    cols = max(2, min(max_cols, int(6.4 / (0.056 * longest + 0.25))))
    body = [f"{esc(n)}{mark(n) if mark else ''}\\par" for n in names]
    return ("{\\setlength{\\multicolsep}{3pt plus 1pt}\\begin{multicols}{%d}\n\\footnotesize\\raggedright\\setlength{\\parindent}{0pt}\\setlength{\\parskip}{0pt}\n"
            % cols + "\n".join(body) + "\n\\end{multicols}}\n")


def heading(text):
    """A bold heading on its own line, kept with the list that follows."""
    return f"\n\\par\\medskip\\noindent\\textbf{{{text}}}\\par\\nopagebreak\\smallskip\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(BOBILIB, "results"))
    ap.add_argument("--out", default=os.path.join(BOBILIB, "paper", "appendix", "generated"))
    a = ap.parse_args()
    R, O = a.results, a.out
    os.makedirs(O, exist_ok=True)
    ins = load(f"{R}/instances.csv")
    I = {r["instance"]: r for r in ins}
    written = []

    def put(fname, text):
        with open(os.path.join(O, fname), "w", newline="\n") as f:
            f.write(text)
        written.append(fname)

    # ---- tab_kip ------------------------------------------------------------------------------
    ss = load(f"{R}/ss/proofs.csv")
    parse = lambda n: tuple(int(x) for x in re.match(r"interKP-(\d+)-100-(\d+)-(\d+)$", n).groups())
    ss.sort(key=lambda r: (parse(r["name"])[1], parse(r["name"])[2], parse(r["name"])[0]))
    assert len(ss) == 16
    rows = []
    for r in ss:
        n, cls, b = parse(r["name"])
        assert int(r["capacity"]) - int(r["optimum"]) == (0 if cls == 6 else 1), r["name"]
        rows.append(" & ".join([esc(r["name"]), str(n), str(cls), str(b), r["budget"], r["capacity"],
                                r["optimum"], r["nodes"], r["cpu_seconds"], r["independent_check_nodes"]]))
    put("tab_kip.tex", longtable(
        "@{}l S[table-format=3.0] S[table-format=1.0] S[table-format=1.0] S[table-format=4.0] S[table-format=4.0] "
        "S[table-format=4.0] S[table-format=5.0] S[table-format=2.2] S[table-format=5.0]@{}",
        "The 16 knapsack interdiction instances without a published optimum, all proven optimal here by the "
        "robust subset-sum search. $n$: items; class 6: subset sum ($p = w$), class 7: even weights and odd "
        "capacity; index: the budget index of the instance name; $\\beta$: the leader's budget; $c$: the "
        "follower's capacity. Every optimum equals $c$ (class 6) or $c-1$ (class 7), the trivial upper bound, "
        "and BOBILib's value. Nodes and CPU seconds of \\texttt{bobi ss-solve} on one thread of a shared machine; "
        "second prover: nodes of \\texttt{scripts/ss\\_check.py}, which shares no code with the search.",
        "tab:kip",
        ["Instance", "{$n$}", "{Class}", "{Index}", "{$\\beta$}", "{$c$}", "{Optimum}", "{Nodes}", "{CPU (s)}",
         "{\\shortstack{Prover\\\\nodes}}"], rows))

    # ---- tab_clique --------------------------------------------------------------------------
    cq = load(f"{R}/clique/summary.csv")
    cq.sort(key=lambda r: natural(r["name"]))
    best3 = []
    for r in cq:
        if r["status"] == "open":
            t = open(f"{R}/clique/runs/deep_tabu_{r['name'].replace('normalClique', '')}.txt").read()
            best3.append((r["name"], int(re.search(r"^best (\d+)", t, re.M).group(1)), r["k"]))
    open_note = (" Open: the best 3-partitions found for " + ", ".join(esc(n) for n, _, _ in best3) + " have "
                 + ", ".join(str(b) for _, b, _ in best3) + f" inside edges, more than $k={best3[0][2]}$, so "
                 "only $3\\le{}$value${}\\le 4$ is known.")
    rows = []
    for r in cq:
        arg = "Mantel" if r["lb_argument"].startswith("Mantel") else "Brouwer${}+w_3(G)>k$"
        m = re.match(r"(\d)-partition with (\d+) inside edges", r["ub_certificate"])
        certif = f"{m.group(1)}-partition, {m.group(2)}"
        status = "optimal" if r["status"] == "optimal" else "\\textbf{open}"
        rows.append(" & ".join([esc(r["name"]), r["n"], r["density"], r["m"], r["k"], r["bobilib_value"],
                                r["lower_bound"], arg, r["upper_bound"], certif, status]))
    put("tab_clique.tex", longtable(
        "@{}l S[table-format=2.0] S[table-format=1.1] S[table-format=4.0] S[table-format=3.0] S[table-format=2.0] "
        "S[table-format=1.0] l S[table-format=1.0] l l@{}",
        "Edge clique interdiction, BOBILib set \\texttt{clique}: $n$ vertices, density $d$, $m$ edges, budget $k$ "
        "(the leader deletes at most $k$ edges). Lower bound: Mantel's theorem ($m-k>\\lfloor n^2/4\\rfloor$, so a "
        "triangle survives) or Brouwer's 1981 Theorem~2 ($m-k\\ge t_3(n)-\\lfloor n/3\\rfloor+2$, so a $K_4$-free "
        "remainder is 3-partite) together with exact solver proofs that every 3-partition has more than $k$ edges "
        "inside its parts ($w_3(G)>k$). Upper bound: the solution file deletes the edges inside an $r$-partition "
        "(certificate: $r$ and the number of inside edges, at most $k$), leaving an $r$-partite graph." + open_note,
        "tab:clique",
        ["Instance", "{$n$}", "{$d$}", "{$m$}", "{$k$}", "{BOBILib}", "{LB}", "Argument", "{UB}", "Certificate",
         "Status"], rows))

    # ---- tab_network -------------------------------------------------------------------------
    net = load(f"{R}/network/summary.csv")
    open_ = [r for r in net if r["bobilib_status"] == "feasible"]
    rows = [" & ".join([esc(r["name"]), r["nodes"], r["edges"], r["phi"], r["lambda"], r["attacks"], r["value"],
                        r["optimal_attacks"], r["bobilib_value"], f"{float(r['secs_enum']):.0f}"]) for r in open_]
    t1 = longtable(
        "@{}l S[table-format=2.0] S[table-format=2.0] S[table-format=1.0] S[table-format=1.0] S[table-format=7.0] "
        "S[table-format=2.0] S[table-format=2.0] S[table-format=2.0] S[table-format=2.0]@{}",
        "The two attack-protect games (\\texttt{inter-fire}) BOBILib lists as feasible, proven optimal by "
        "enumerating every attack of at most $\\Phi$ nodes, with the follower (protect at most $\\Lambda$ nodes) "
        "solved exactly by a tree dynamic program and the minimiser re-solved by HiGHS. Time: wall seconds of the "
        "enumeration on one thread of a loaded machine.",
        "tab:network",
        ["Instance", "{Nodes}", "{Edges}", "{$\\Phi$}", "{$\\Lambda$}", "{Attacks}", "{Optimum}",
         "{\\shortstack{Optimal\\\\attacks}}", "{BOBILib}", "{Time (s)}"], rows)
    groups = collections.OrderedDict()
    for r in sorted(net, key=lambda r: natural(r["name"])):
        if r["bobilib_status"] != "optimal":
            continue
        g = r["name"].rsplit("_", 1)[0]
        groups.setdefault(g, []).append(r)
    rows = []
    tot = 0
    for g, rs in groups.items():
        vals = sorted(int(r["value"]) for r in rs)
        agree = sum(r["agrees"] == "true" and r["certified"] == "true" and r["value"] == r["bobilib_value"] for r in rs)
        tot += agree
        vtxt = ", ".join(str(v) for v in vals)
        rows.append(" & ".join([esc(g), str(len(rs)), rs[0]["nodes"], rs[0]["phi"], rs[0]["lambda"], rs[0]["attacks"],
                                vtxt, f"{agree}/{len(rs)}"]))
    assert tot == 34 and sum(len(v) for v in groups.values()) == 34
    t2 = longtable(
        "@{}l S[table-format=1.0] S[table-format=2.0] S[table-format=1.0] S[table-format=1.0] S[table-format=7.0] l l@{}",
        "The 34 tree instances BOBILib lists as optimal, re-derived by the same enumeration: instances per group, "
        "nodes (after removing the vaccinated ones), budgets, attacks per instance, the optimal values found, "
        "and how many equal BOBILib's value with a certified solution file.",
        "tab:network-trees",
        ["Group", "{Inst.}", "{Nodes}", "{$\\Phi$}", "{$\\Lambda$}", "{Attacks}", "Optima", "Agree"], rows)
    put("tab_network.tex", t1 + "\n" + t2.replace(HEADER, ""))

    # ---- tab_rays ----------------------------------------------------------------------------
    rv = {}
    for line in open(f"{R}/rays/ray_verify.jsonl"):
        if line.startswith("{"):
            d = json.loads(line)
            n = d["instance"].replace(".mps.gz", "")
            if d["verified"] or n not in rv:
                rv[n] = d
    rays = sorted((r for r in ins if r["new_status"] == "infeasible_bilevel"), key=lambda r: natural(r["instance"]))
    assert len(rays) == 40
    rows = []
    for r in rays:
        d = rv[r["instance"]]
        rows.append(" & ".join([esc(r["instance"]), esc(r["collection"]), str(d["support"]),
                                dec(d["objective_along_d"], 4), "yes" if d["verified"] else "no (floating point)"]))
    put("tab_rays.tex", longtable(
        "@{}l l S[table-format=5.0] S[table-format=-9.4] l@{}",
        "The 40 open MIPLIB-derived instances with no bilevel feasible point: the follower's own rows admit a "
        "recession direction $r$ (follower variables only) with $f^\\top r<0$, for every leader choice (Meyer "
        "1974). Support: nonzero entries of $r$; $f^\\top r$ rounded to four decimals; exact: checked in exact "
        "rational arithmetic by \\texttt{scripts/verify\\_ray.py} (the two supportcase42 directions leave "
        "residuals of about $10^{-12}$ relative and rest on floating point).",
        "tab:rays",
        ["Instance", "Collection", "{Support}", "{$f^\\top r$}", "Exact"], rows))

    # ---- tab_hpr -----------------------------------------------------------------------------
    hpr = load(f"{R}/general/hpr_optimal.csv")
    rows = []
    for r in hpr:
        row = I[r["name"]]
        if not (row["new_status"] == "optimal" and row["source"] == "this work"):
            continue
        if "general-coupled" in r["point_from"]:
            src = "\\texttt{bobi coupled}"
        elif "results/general/" in r["point_from"]:
            src = "\\texttt{bobi general}"
        else:
            src = "BOBILib's solution file"
        mip = r["miplib_optimum"]
        rows.append(" & ".join([esc(r["name"]), r["bobilib_status"], esc(r["miplib_instance"]),
                                f"\\num{{{mip}}}", f"\\num{{{r['optimum']}}}", src]))
    assert len(rows) == 5
    put("tab_hpr.tex", longtable(
        "@{}l l l r r l@{}",
        "Five MIPLIB-derived instances whose high point relaxation is exactly the MIPLIB model they were built "
        "from (checked in exact arithmetic by \\texttt{scripts/compare\\_hpr.py}), so the published MIPLIB "
        "optimum (MIPLIB 2017's solution file) is a lower bound; a verified bilevel feasible point at that value "
        "is optimal. The objective of noswot takes integer values only, so its bound rounds up to $-41$. "
        "Status: BOBILib's "
        "before this work. (neos-950242\\_0\\_100 meets its bound too, but was already listed as optimal in an "
        "earlier BOBILib release and is counted as published.)",
        "tab:hpr",
        ["Instance", "BOBILib", "MIPLIB instance", "MIPLIB optimum", "Bilevel optimum", "Point from"], rows))

    # ---- tab_general_points --------------------------------------------------------------------
    gp = {r["name"]: r for r in load(f"{R}/general/points.csv")}
    cp = {r["name"]: r for r in load(f"{R}/general-coupled/summary.csv")}
    pts = sorted((r for r in ins if r["new_status"] == "feasible" and r["family"].startswith("general-")),
                 key=lambda r: natural(r["instance"]))
    assert len(pts) == 90
    rows, tol, pub = [], 0, 0
    for r in pts:
        if r["certificate"].startswith("general-coupled/"):
            c = cp[r["instance"]]
            coup, meth, low = "yes", c["method"], num(c["lower_obj"])
            mark = "$^{*}$" if (num(c["rel_error"]) or 0) > 1e-8 else ""
            tol += bool(mark)
        else:
            g = gp[r["instance"]]
            coup, meth, low, mark = "no", "hpr-f-t", num(g["lower_obj"]), ""
        if "published point" in r["notes"]:
            mark += "$^{\\ddagger}$"
            pub += 1
        rows.append(" & ".join([esc(r["instance"]) + mark, esc(r["collection"]), coup, meth,
                                dec(num(r["primal_value"])), dec(low)]))
    assert tol == 9 and pub == 10, (tol, pub)
    put("tab_general_points.tex", longtable(
        "@{}l l c l S[table-format=-10.4] S[table-format=-10.4]@{}",
        "The 90 verified bilevel feasible points for open MIPLIB-derived instances, for which BOBILib lists no "
        "point. $^{\\ddagger}$: a point had been published elsewhere (its value and source are in the notes of "
        "\\texttt{instances.csv}); for the other 80 this is the first point known. Coupling: "
        "whether leader rows contain follower variables. Method: \\texttt{hpr-f-t}, the high point relaxation, "
        "then the follower solved with the leader fixed, then an optimistic tie-break (\\texttt{bobi general}); "
        "\\texttt{hpr}, \\texttt{penalty}, \\texttt{follow}: the part of the \\texttt{bobi coupled} portfolio "
        "that found the point (the HPR's own leader values, a penalised HPR, best-response dynamics). Values "
        "rounded to four decimals (full precision in \\texttt{instances.csv}); the leader minimises, so does the "
        "follower. $^{*}$: the follower's value is about $10^{-7}$ relative above its optimum, inside BOBILib's "
        "tolerance of $10^{-4}$. Three further points are optimal (Table~\\ref{tab:hpr}).",
        "tab:general-points",
        ["Instance", "Collection", "Coupling", "Method", "{Leader value}", "{Follower value}"], rows))

    # ---- tab_or --------------------------------------------------------------------------------
    orr = load(f"{R}/or/compare.csv")
    key = lambda r: (int(r["m"]), int(r["n"]), r["alpha"], int(r["variant"]),
                     int(re.search(r"_(\d+)\.dat", r["name"]).group(1)))
    orr.sort(key=key)
    rows, flagged = [], 0
    for r in orr:
        row = I[r["name"]]
        fr = {"0": int(r["m"]) - 1, "50": int(r["m"]) // 2, "100": 1}[r["variant"]]
        ll, lu, ol, op = num(r["lit_lb"]), num(r["lit_ub"]), num(r["our_lb"]), num(r["our_point"])
        gap = num(r["gap"])
        name = esc(r["name"])
        if ll is not None and lu is not None and ll > lu:  # published bounds contradict each other
            flagged += 1
            name += "$^{\\dagger}$"
            lb = num(row["dual_bound"])
            ubs = [x for x in (op, num(r["our_lp_bound"]), num(row["primal_value"])) if x is not None]
            gap = (min(ubs) - lb) / min(ubs) if ubs and lb is not None else None
        status = row["new_status"]
        g = "" if gap is None else f"{100 * max(gap, 0):.2f}"
        if status == "optimal":
            g = "0.00"
        rows.append(" & ".join([name, f"{int(round(100 * float(r['alpha'])))}", str(fr), intval(ll), intval(lu),
                                intval(num(r["bobilib"])), intval(ol), intval(op), g]))
    assert flagged == 4
    put("tab_or.tex", longtable(
        "@{}l S[table-format=2.0] S[table-format=2.0] S[table-format=6.0] S[table-format=6.0] S[table-format=6.0] "
        "S[table-format=6.0] S[table-format=6.0] S[table-format=3.2]@{}",
        "All 810 multidimensional knapsack interdiction instances of the OR set; names have the form "
        "\\texttt{OR}\\emph{rows}\\texttt{x}\\emph{items}\\texttt{-}\\allowbreak\\emph{budget}"
        "\\texttt{\\_}\\emph{i}\\texttt{.dat-}\\allowbreak\\emph{variant}. Budget: the tightness $\\alpha$ in percent (the right-hand side of every knapsack row, leader's and "
        "follower's, is $\\alpha$ times the sum of its coefficients); follower rows: "
        "knapsack rows of the follower (variant -100: one; -0 and -50: several). Published LB: Lozano, Bergman "
        "and Cire (2026); published UB: best published point (Lozano, Bergman and Cire, or Lefebvre and Schmidt "
        "(2025); not verified here); BOBILib: BOBILib's best known value; our LB: "
        "dualised follower LP bracket or merged-row online bound (one follower knapsack only); our point: "
        "verified solution file; gap: (best upper bound $-$ best lower bound)/best upper bound in percent, where "
        "the best upper bound may be the follower LP bound at our leader choice (100: no lower bound known). "
        "Blank: none. "
        "$^{\\dagger}$: the published lower bound exceeds the published point (inconsistent sources); the gap "
        "then leaves the published point out, and OR10x100-0.75\\_4.dat-0 is closed at 8,813, the authors' "
        "branch-and-cut bound.",
        "tab:or",
        ["Instance", "{Budget}", "{\\shortstack{Foll.\\\\rows}}", "{\\shortstack{Publ.\\\\LB}}",
         "{\\shortstack{Publ.\\\\UB}}", "{BOBILib}", "{\\shortstack{Our\\\\LB}}", "{\\shortstack{Our\\\\point}}",
         "{\\shortstack{Gap\\\\(\\%)}}"], rows, colsep="3.5pt"))

    # ---- tab_or_conflicts: published bounds that contradict each other ----------------------------
    mk = {r["name"]: r for r in load(f"{R}/literature/mkip_literature_status.csv")}
    rows = []
    for r in orr:
        ll, lu = num(r["lit_lb"]), num(r["lit_ub"])
        if ll is None or lu is None or ll <= lu:
            continue
        m = mk[r["name"]]
        dd, ls_ = num(m["dd_lcb2026_ub"]), num(m["lefebvre_schmidt_ub"])
        src = ("Lefebvre--Schmidt" if ls_ is not None and ls_ == lu else
               "Lozano et al." if dd is not None and dd == lu else "published")
        row = I[r["name"]]
        treat = ("closed (Section~\\ref{app:mkip-or}); not paired" if row["new_status"] == "optimal" else
                 "not in the paired medians")
        rows.append(" & ".join([esc(r["name"]), intval(ll), intval(lu), src, intval(dd), intval(num(r["our_point"])),
                                treat]))
    assert len(rows) == 4
    put("tab_or_conflicts.tex", longtable(
        "@{}l S[table-format=5.0] S[table-format=6.0] l S[table-format=6.0] S[table-format=5.0] l@{}",
        "The OR instances whose published lower bound (Lozano, Bergman and Cire) exceeds the best published "
        "point. Point source: who published that point; Lozano et al.'s point: their own published point; our "
        "point: the verified solution file of this work (blank: none). Lefebvre and Schmidt's three values come "
        "from runs that stopped at a time or solution limit and lie below a published lower bound; they are not "
        "verified here. The paper's paired median gaps leave these instances out.",
        "tab:or-conflicts",
        ["Instance", "{\\shortstack{Publ.\\\\LB}}", "{\\shortstack{Publ.\\\\point}}", "Point source",
         "{\\shortstack{Lozano\\\\et al.}}", "{\\shortstack{Our\\\\point}}", "Here"], rows, colsep="4pt"))

    # ---- tab_literature ------------------------------------------------------------------------
    lit = [r for r in ins if r["bobilib_status"] in ("feasible", "open") and r["new_status"] == "optimal"
           and r["source"] != "this work"]
    assert len(lit) == 528
    bysrc = collections.defaultdict(list)
    for r in lit:
        bysrc[r["source"]].append(r)
    order = sorted(bysrc, key=lambda k: -len(bysrc[k]))
    rows = []
    for k in order:
        rs = bysrc[k]
        fams = collections.Counter(r["collection"] for r in rs)
        rows.append(" & ".join([SOURCE_TEXT[k], ", ".join(f"{esc(c)} {n}" for c, n in sorted(fams.items(), key=lambda x: -x[1])),
                                str(len(rs))]))
    rows.append("\\midrule")
    rows.append(" & ".join(["Total", "", str(len(lit))]))
    txt = longtable(
        "@{}p{0.6\\linewidth} l S[table-format=3.0]@{}",
        "Published optima for instances BOBILib lists as feasible or open, by source (sub-collection and count). "
        "The instance names follow.",
        "tab:literature", ["Source", "Collections", "{Instances}"], rows)
    for k in order:
        names = sorted((r["instance"] for r in bysrc[k]), key=natural)
        txt += heading(f"{SOURCE_TEXT[k][0].upper() + SOURCE_TEXT[k][1:]} ({len(names)})") + name_list(names)
    put("tab_literature.tex", txt)

    # ---- tab_unchanged -------------------------------------------------------------------------
    unch = [r for r in ins if r["bobilib_status"] in ("feasible", "open") and r["new_status"] == "unchanged"]
    assert len(unch) == 716
    byfam = collections.defaultdict(list)
    for r in unch:
        byfam[r["family"]].append(r)
    forder = sorted(byfam, key=lambda k: -len(byfam[k]))
    rows = []
    better = {r["instance"] for r in unch if r["source"] == "this work"}
    for f in forder:
        rs = byfam[f]
        cols = collections.Counter(r["collection"] for r in rs)
        rows.append(" & ".join([FAMILY_TEXT[f], ", ".join(f"{esc(c)} {n}" for c, n in sorted(cols.items(), key=lambda x: -x[1])),
                                str(sum(r["bobilib_status"] == "feasible" for r in rs)),
                                str(sum(r["bobilib_status"] == "open" for r in rs)),
                                str(sum(r["instance"] in better for r in rs)), str(len(rs))]))
    rows.append("\\midrule")
    rows.append(" & ".join(["Total", "", str(sum(r["bobilib_status"] == "feasible" for r in unch)),
                            str(sum(r["bobilib_status"] == "open" for r in unch)), str(len(better)), str(len(unch))]))
    txt = longtable(
        "@{}l p{0.34\\linewidth} S[table-format=3.0] S[table-format=3.0] S[table-format=3.0] S[table-format=3.0]@{}",
        "Instances whose BOBILib status is unchanged, by family: BOBILib status (feasible or open), and how many "
        "now have a verified point better than BOBILib's (marked $^{*}$ in the lists below).",
        "tab:unchanged", ["Family", "Collections", "{Feasible}", "{Open}", "{Better point}", "{Total}"], rows)
    for f in forder:
        names = sorted((r["instance"] for r in byfam[f]), key=natural)
        txt += (heading(f"{FAMILY_TEXT[f][0].upper() + FAMILY_TEXT[f][1:]} ({len(names)})")
                + name_list(names, mark=lambda n: "$^{*}$" if n in better else ""))
    put("tab_unchanged.tex", txt)

